import type { Brand } from "../../shared/ids/brand";
import { unsafeBrand } from "../../shared/ids/brand";
import { err, ok, type Result } from "../../shared/result/result";
import { primitiveError, type PrimitiveError } from "../primitives/errors";

/**
 * Every domain identifier is a branded string. Two families exist:
 *
 *  - *Authored* identifiers (`ProcedureId`, `RuleId`, `DocumentTypeId`, ...)
 *    are stable, human-readable slugs owned by the knowledge base. They are
 *    authored, reviewed and referenced by rules, so they must be readable and
 *    stable - never random.
 *  - *Record* identifiers (`UserCaseId`, `CaseEvaluationId`, ...) identify rows
 *    and are UUIDs generated by the database.
 *
 * Derived keys (`RequiredProcedureKey`, `RequiredDocumentKey`) are neither:
 * they are deterministic functions of semantic content and are generated by
 * `case-engine/canonicalization`. They must never be random UUIDs.
 */
const SLUG_PATTERN = /^[a-z0-9]+(?:[-.][a-z0-9]+)*$/u;
const UUID_PATTERN = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/u;

function makeSlugId<Tag extends string>(
  tag: Tag,
  value: string,
  maxLength = 96,
): Result<Brand<string, Tag>, PrimitiveError> {
  if (value.length === 0 || value.length > maxLength) {
    return err(primitiveError(tag, `length must be 1..${maxLength}, received ${value.length}`));
  }
  if (!SLUG_PATTERN.test(value)) {
    return err(
      primitiveError(tag, `expected lower-case dotted/dashed slug, received "${value}"`),
    );
  }
  return ok(unsafeBrand<string, Tag>(value));
}

function makeUuidId<Tag extends string>(tag: Tag, value: string): Result<Brand<string, Tag>, PrimitiveError> {
  if (!UUID_PATTERN.test(value)) {
    return err(primitiveError(tag, `expected a UUID, received "${value}"`));
  }
  return ok(unsafeBrand<string, Tag>(value));
}

