/**
 * Deterministic identity of a required procedure within one evaluation.
 * Format v1: `rp1:<procedureId>|<canonical parameters>[|<discriminator>]`.
 */
export type RequiredProcedureKey = Brand<string, "RequiredProcedureKey">;

/**
 * Deterministic identity of a required document within one evaluation.
 * Format v1: `rd1:<requiredProcedureKey>|<documentTypeId>|<issuingCountry>|<discriminator>`.
 */
export type RequiredDocumentKey = Brand<string, "RequiredDocumentKey">;

/**
 * Only the canonicalization module in `case-engine` may mint derived keys, and
 * only from canonical semantic content.
 */
export function unsafeRequiredProcedureKey(value: string): RequiredProcedureKey {
  return unsafeBrand<string, "RequiredProcedureKey">(value);
}

export function unsafeRequiredDocumentKey(value: string): RequiredDocumentKey {
  return unsafeBrand<string, "RequiredDocumentKey">(value);
}

